    startDrive(false);
    let s = 0;
    let t = Date.now();
    S.simTimer = setInterval(() => {
      s += 12;
      t += 1000;
      if (s > R.len) { stopSim(); return; }
      const [x, y] = pointAt(R, s);
      const [lat, lon] = fromXY(x + (Math.random() - 0.5) * 8, y + (Math.random() - 0.5) * 8);
      onFix({ lat, lon, acc: 8, t });
    }, 250);
