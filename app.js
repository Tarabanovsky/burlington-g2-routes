  const OFF_ROUTE_FIXES = 3;    // consecutive misses before telling the driver they're off route
  const MAX_SPEED_MPS = 45;     // faster jumps between fixes are GPS glitches
  const WEAK_ACCURACY_M = 75;
  const TIE_M = 12;             // candidates this close to the best are ties; heading breaks them
  const MOVING_MPS = 2.5;       // below this, GPS heading is noise (stopped, reversing, parking)
  const HEADING_TTL_MS = 30000;
  const STALE_MS = 12000;       // no fix for this long: tell the driver GPS has paused
  const RESTART_WATCH_MS = 15000;
  const LOG_MAX = 3000;
  const SAY_FAR_M = 160;
  const SAY_NEAR_M = 90;
  const RESUME_MS = 10 * 60 * 1000;
  const WIDE = '(min-width: 860px), (orientation: landscape) and (min-width: 600px)';

  const touch = window.matchMedia('(pointer: coarse)').matches;
  const S = {
    routeId: store.get('route', D.routes[0].id),
    mode: store.get('mode', touch && 'geolocation' in navigator ? 'live' : 'tap'),
    voice: store.get('voice', false),
    idx: 0, s: 0, locked: false, off: 0, last: null, heading: null, headingAt: 0,
    v: 0, lastGood: null, hist: [],
    follow: true, running: false, watchId: null, simTimer: null, wake: null,
    spoken: {}, shownIdx: -1, fix: null, finishedSaid: false,
    lastFixAt: 0, watchStartedAt: 0, log: [],
  };
  if (!D.routes.some((r) => r.id === S.routeId)) S.routeId = D.routes[0].id;
  let R = null;

  // Local planar projection (metres) around the test centre.
  const LAT0 = D.centre.lat;
  const LON0 = D.centre.lon;
  const KX = 111320 * Math.cos(LAT0 * Math.PI / 180);
  const KY = 110574;
  const toXY = (lat, lon) => [(lon - LON0) * KX, (lat - LAT0) * KY];
  const fromXY = (x, y) => [LAT0 + y / KY, LON0 + x / KX];
  D.routes.forEach((r) => { r.xy = r.pts.map((p) => toXY(p[0], p[1])); r.len = r.cum[r.cum.length - 1]; });

  // ---------- Geometry ----------
  // Nearest point on the route between sMin and sMax. Where the route passes the same spot twice
  // (out-and-back streets, shared roads), near-ties are split by direction of travel, then by
  // closeness to where the car should be by now. Heading never decides whether a fix is on the route.
  function project(r, x, y, sMin, sMax, heading, expected) {
    const cands = [];
    for (let i = 0; i < r.xy.length - 1; i++) {
      if (r.cum[i + 1] < sMin || r.cum[i] > sMax) continue;
      const [ax, ay] = r.xy[i];
      const [bx, by] = r.xy[i + 1];
      const dx = bx - ax;
      const dy = by - ay;
      const l2 = dx * dx + dy * dy;
      let t = l2 ? ((x - ax) * dx + (y - ay) * dy) / l2 : 0;
      t = Math.max(0, Math.min(1, t));
      const s = Math.max(sMin, Math.min(sMax, r.cum[i] + t * (r.cum[i + 1] - r.cum[i])));
      const d = Math.hypot(x - (ax + t * dx), y - (ay + t * dy));
      let wrongWay = false;
      if (heading != null && l2 > 4) {
        const seg = (Math.atan2(dx, dy) * 180 / Math.PI + 360) % 360;
        wrongWay = Math.abs(((heading - seg + 540) % 360) - 180) > 100;
      }
      cands.push({ s, d, wrongWay });
    }
    if (!cands.length) return null;
    const dmin = Math.min(...cands.map((c) => c.d));
    let ties = cands.filter((c) => c.d <= dmin + TIE_M);
    if (ties.some((c) => !c.wrongWay)) ties = ties.filter((c) => !c.wrongWay);
    const rank = expected == null ? (c) => c.s : (c) => Math.abs(c.s - expected);
    return ties.sort((a, b) => rank(a) - rank(b))[0];
  }

  function pointAt(r, s) {
    let i = 0;
    while (i < r.cum.length - 2 && r.cum[i + 1] < s) i++;
    const a = r.cum[i];
    const b = r.cum[i + 1];
    const t = b > a ? Math.min(1, Math.max(0, (s - a) / (b - a))) : 0;
    return [r.xy[i][0] + (r.xy[i + 1][0] - r.xy[i][0]) * t, r.xy[i][1] + (r.xy[i + 1][1] - r.xy[i][1]) * t];
  }

  function sliceLine(r, from, to) {
    const out = [];
    for (let i = 0; i < r.pts.length - 1; i++) {
      const a = r.cum[i];
      const b = r.cum[i + 1];
      if (b < from || a > to) continue;
      const lerp = (s) => {
        const t = b > a ? (s - a) / (b - a) : 0;
        return [r.pts[i][0] + (r.pts[i + 1][0] - r.pts[i][0]) * t, r.pts[i][1] + (r.pts[i + 1][1] - r.pts[i][1]) * t];
      };
      if (!out.length) out.push(a >= from ? r.pts[i] : lerp(from));
      out.push(b <= to ? r.pts[i + 1] : lerp(to));
    }
    return out;
  }

  // ---------- Map ----------
  const map = L.map('map', { zoomControl: true });
  L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png', {
    maxZoom: 19,
    attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors',
  }).addTo(map);
  const lineLayer = L.layerGroup().addTo(map);
  const cpLayer = L.layerGroup().addTo(map);
  const doneLine = L.polyline([], { color: '#8a94a3', weight: 7, opacity: 0.95, interactive: false });
  const meAcc = L.circle([LAT0, LON0], { radius: 1, color: '#1a73e8', weight: 1, fillOpacity: 0.12, interactive: false });
  const meDot = L.circleMarker([LAT0, LON0], { radius: 8, color: '#fff', weight: 3, fillColor: '#1a73e8', fillOpacity: 1, interactive: false });
  let cpMarkers = [];

  L.marker([D.centre.lat, D.centre.lon], {
    zIndexOffset: 900,
    icon: L.divIcon({ className: '', iconSize: [26, 26], iconAnchor: [13, 13], html: '<div class="centre-dot">DT</div>' }),
  }).bindPopup(`<b>${esc(D.centre.name)}</b><br>${esc(D.centre.address)}`).addTo(map);
  D.areas.forEach((a) => {
    L.marker([a.lat, a.lon], {
      icon: L.divIcon({ className: '', iconSize: [14, 14], iconAnchor: [7, 7], html: '<div class="area-dot"></div>' }),
    }).bindPopup(`<b>${esc(a.name)}</b><br>${esc(a.note)}`).addTo(map);
  });

  map.on('dragstart', () => {
    if (S.mode === 'live' && S.running) { S.follow = false; $('#recenter').hidden = false; }
  });
  $('#recenter').onclick = () => {
    S.follow = true;
    $('#recenter').hidden = true;
    if (S.fix) map.setView([S.fix.lat, S.fix.lon], Math.max(map.getZoom(), 17));
  };

  function cpIcon(i, state) {
    const big = state === 'current';
    return L.divIcon({
      className: '', iconSize: big ? [30, 30] : [22, 22], iconAnchor: big ? [15, 15] : [11, 11],
      html: `<div class="cp-dot ${state}">${i + 1}</div>`,
    });
  }

  function drawRoute() {
    lineLayer.clearLayers();
    cpLayer.clearLayers();
    const cps = R.checkpoints;
    const exitAt = cps[0].at;
    const enter = cps.find((c) => c.kind === 'enter');
    const enterAt = enter ? enter.at : R.len;
    const lot = { color: '#6b7685', weight: 4, opacity: 0.8, dashArray: '2 7', lineCap: 'round' };
    L.polyline(sliceLine(R, 0, exitAt), lot).bindTooltip('Inside the plaza: any way to the exit').addTo(lineLayer);
    L.polyline(sliceLine(R, enterAt, R.len), lot).bindTooltip('Inside the plaza: park where the examiner says').addTo(lineLayer);
    L.polyline(sliceLine(R, exitAt, R.return_at), { color: R.color, weight: 7, opacity: 0.9 }).addTo(lineLayer);
    L.polyline(sliceLine(R, R.return_at, enterAt), { color: R.color, weight: 6, opacity: 0.8, dashArray: '10 9' })
      .bindTooltip('Drive back to the centre (inferred, not in any source)').addTo(lineLayer);
    doneLine.setLatLngs([]).addTo(lineLayer);
    cpMarkers = R.checkpoints.map((c, i) => L.marker([c.lat, c.lon], { icon: cpIcon(i, ''), zIndexOffset: 400 })
      .on('click', () => onCheckpointTap(i)).addTo(cpLayer));
    document.documentElement.style.setProperty('--c', R.color);
  }

